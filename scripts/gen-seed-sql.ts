// Generates supabase/seed.sql from src/lib/seed.ts so the SQL seed and the
// local preview store can never drift apart.
// Run: npm run gen:seed
import {
  DAY,
  FLAG_REASON_SEED,
  SEED_CAMPAIGNS,
  SEED_ENTITIES,
  SEED_PAYMENTS,
  SEED_PAYMENT_REASON,
  seedCallEntityRows,
  seedCallRows,
  seedCampaignFirstSeenAgo,
} from "../src/lib/seed.ts";

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const ago = (s: number) => `now() - interval '${Math.round(s)} seconds'`;

const lines: string[] = [];
const out = (s: string) => lines.push(s);

out("-- Generated by scripts/gen-seed-sql.ts. Do not edit by hand.");
out("-- Defines reset_demo() (plan section 11.6) and runs it once to load the seed.");
out("create or replace function reset_demo() returns void language plpgsql security definer as $$");
out("begin");
out("  -- delete (not truncate) so Realtime sends change events to every screen");
for (const t of [
  "coaching_checks",
  "canary_hits",
  "reports",
  "timeline_events",
  "payments",
  "call_entities",
  "transcript_lines",
  "entities",
  "calls",
  "campaigns",
  "counters",
  "demo_sessions",
]) {
  out(`  delete from ${t} where true;`);
}

out("");
for (const c of SEED_CAMPAIGNS) {
  out(
    `  insert into campaigns (id, name, scam_type, region, first_seen_at) values (${q(c.id)}, ${q(c.name)}, ${q(
      c.scam_type,
    )}, ${q(c.region)}, ${ago(seedCampaignFirstSeenAgo(c.id))});`,
  );
}

out("");
for (const c of seedCallRows()) {
  out(
    `  insert into calls (id, source, status, started_at, ended_at, duration_seconds, scam_type, impersonated_org, summary, confidence, campaign_id) values (${q(
      c.id,
    )}, 'seed', 'ended', ${ago(c.startedAgo)}, ${ago(c.endedAgo)}, ${c.duration_seconds}, ${q(c.scam_type)}, ${q(
      c.impersonated_org,
    )}, ${q(c.summary)}, ${c.confidence}, ${q(c.campaign_id)});`,
  );
}

const ce = seedCallEntityRows();
out("");
for (const e of SEED_ENTITIES) {
  const firstUse = Math.max(...ce.filter((r) => r.entity_id === e.id).map((r) => r.createdAgo));
  const flagged = e.flaggedDaysAgo !== null;
  out(
    `  insert into entities (id, kind, value, display, label, flagged, flagged_at, flag_reason, first_seen_at) values (${q(
      e.id,
    )}, ${q(e.kind)}, ${q(e.value)}, ${q(e.display)}, ${q(e.label)}, ${flagged}, ${
      flagged ? ago(e.flaggedDaysAgo! * DAY) : "null"
    }, ${flagged ? q(FLAG_REASON_SEED) : "null"}, ${ago(firstUse)});`,
  );
}

out("");
for (const r of ce) {
  out(
    `  insert into call_entities (call_id, entity_id, found_by, confirmed, created_at) values (${q(r.call_id)}, ${q(
      r.entity_id,
    )}, 'seed', true, ${ago(r.createdAgo)});`,
  );
}

out("");
for (const p of SEED_PAYMENTS) {
  const e = SEED_ENTITIES.find((x) => x.key === p.entityKey)!;
  const [sort, acct] = e.value.split(":");
  out(
    `  insert into payments (id, payee_name, sort_code, account_number, amount_pence, status, reason, entity_id, created_at) values (${q(
      p.id,
    )}, ${q(p.payee_name)}, ${q(sort)}, ${q(acct)}, ${p.amount_pence}, 'paused', ${q(SEED_PAYMENT_REASON)}, ${q(
      e.id,
    )}, ${ago(p.daysAgo * DAY)});`,
  );
}

out("");
out("  insert into counters (id, calls_taken, seconds_wasted, accounts_flagged, payments_paused, value_protected_pence)");
out("  select 'demo',");
out("         (select count(*) from calls),");
out("         (select coalesce(sum(duration_seconds),0) from calls),");
out("         (select count(*) from entities where flagged),");
out("         (select count(*) from payments where status = 'paused'),");
out("         (select coalesce(sum(amount_pence),0) from payments where status = 'paused');");
out("");
out("  insert into demo_sessions (id) values ('demo');");
out("  insert into timeline_events (kind, title) values ('system', 'Demo reset');");
out("end;");
out("$$;");
out("");
out("select reset_demo();");

process.stdout.write(lines.join("\n") + "\n");
